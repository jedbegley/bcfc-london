import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {test} from 'node:test';
const {PGlite}=await import(process.env.BCFC_PGLITE_MODULE||'@electric-sql/pglite');
test('app usage, permissions, opt-in, manual announcements, closed fixtures and duplicate prevention',async(t)=>{
 const db=new PGlite();t.after(()=>db.close());
 await db.exec(`
 create role anon;create role authenticated;create role service_role bypassrls;
 create schema auth;create schema vault;create schema net;
 create table auth.users(id uuid primary key,email text);
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema auth to authenticated,service_role;
 create table vault.decrypted_secrets(name text,decrypted_secret text);
 create function net.http_post(url text,headers jsonb,body jsonb,timeout_milliseconds integer) returns bigint language sql as $$select 1::bigint$$;
 create table public."Players"(id bigint primary key,full_name text,user_id uuid,is_admin boolean);
 create function public.current_user_is_admin() returns boolean language sql stable security definer set search_path='' as $$select exists(select 1 from public."Players" where user_id=auth.uid() and is_admin)$$;
 create table public.matches(id bigint primary key,opponent text,match_date date,status text,availability_open boolean);
 insert into auth.users values('00000000-0000-0000-0000-000000000001','manager@example.com'),('00000000-0000-0000-0000-000000000002','player@example.com');
 insert into public."Players" values(1,'Manager','00000000-0000-0000-0000-000000000001',true),(2,'Player','00000000-0000-0000-0000-000000000002',false);
 grant select on public."Players",matches to authenticated;
 insert into matches values(9,'Closed',current_date+7,'Upcoming',false),(10,'Open',current_date+7,'Upcoming',true),(8,'Report',current_date-1,'Completed',true);
 `);
 await db.exec(await readFile(new URL('../supabase/migrations/20261023143952_app_push_notifications.sql',import.meta.url),'utf8'));
 const rows=async sql=>(await db.query(sql)).rows;
 await db.exec(`insert into app_push_config(public_key) values('public-test-key');set request.jwt.claim.sub='00000000-0000-0000-0000-000000000002';set role authenticated;`);
 await assert.rejects(db.exec('select * from public.app_usage_summary()'),/Manager access required/);
 await assert.rejects(db.exec(`select public.queue_app_announcement('news','story','News','Body')`),/Manager access required/);
 await assert.rejects(db.exec(`select public.app_push_worker_config(repeat('a',64))`),/permission denied/);
 const installation='00000000-0000-0000-0000-000000000012';
 const sub=JSON.stringify({endpoint:'https://fcm.googleapis.com/fcm/send/test-player',keys:{p256dh:'B'.repeat(87),auth:'A'.repeat(22)}});
 await db.exec(`select public.record_app_device('${installation}',false,'default');`);
 await db.exec('reset role');
 assert.equal((await rows('select first_app_use from app_devices'))[0].first_app_use,null);
 await db.exec(`set role authenticated;select public.record_app_device('${installation}',true,'granted','${sub}'::jsonb);`);
 await assert.rejects(db.exec(`select public.record_app_device('${installation}',true,'granted','${sub.replace('https://fcm.googleapis.com/fcm/send/test-player','http://127.0.0.1/admin')}'::jsonb)`),/Invalid push subscription/);
 await assert.rejects(db.exec('select endpoint from public.app_devices'),/permission denied/);
 await db.exec(`select public.queue_app_push_test('${installation}');reset role;`);
 assert.equal((await rows('select count(*)::int n from app_push_deliveries'))[0].n,1);
 await db.exec(`set request.jwt.claim.sub='00000000-0000-0000-0000-000000000001';set role authenticated;`);
 const usage=await rows('select * from public.app_usage_summary()');
 assert(usage.find(p=>p.full_name==='Player').last_app_use);
 assert.equal(Number(usage.find(p=>p.full_name==='Player').subscribed_devices),1);
 await assert.rejects(db.exec(`select public.queue_app_announcement('news','story','News','Body')`),/awaiting the phone test/);
 await db.exec('reset role;update app_push_config set broadcasts_enabled=true;set role authenticated;');
 await assert.rejects(db.exec(`select public.queue_app_announcement('availability','9','Available','Please respond')`),/must be open/);
 const first=(await rows(`select public.queue_app_announcement('news','story','New story','Read the story') result`))[0].result;
 assert.equal(first.devices,1);
 const duplicate=(await rows(`select public.queue_app_announcement('news','story','New story','Read the story') result`))[0].result;
 assert.equal(duplicate.already_sent,true);
 await db.exec('reset role;set role service_role;');
 assert.equal((await rows('select * from public.claim_app_push_deliveries()')).length,2);
 assert.equal((await rows('select * from public.claim_app_push_deliveries()')).length,0);
 await db.exec(`reset role;update app_push_deliveries set leased_until=now()-interval '1 minute';set role service_role;select * from public.claim_app_push_deliveries();reset role;`);
 assert.equal((await rows("select count(*)::int n from app_push_deliveries where state='needs_review'"))[0].n,2);
 await db.exec(`set request.jwt.claim.sub='00000000-0000-0000-0000-000000000002';set role authenticated;insert into app_push_preferences(user_id,news)values(auth.uid(),false);reset role;set request.jwt.claim.sub='00000000-0000-0000-0000-000000000001';set role authenticated;`);
 await assert.rejects(db.exec(`select public.queue_app_announcement('news','another-story','News','Body')`),/No subscribed devices/);
 await db.exec(`select public.queue_app_announcement('availability','10','Available','Please respond');select public.queue_app_announcement('report','8','Report','Vote MOTM');reset role;`);
 assert.equal((await rows("select count(*)::int n from app_push_messages where kind='news'"))[0].n,1);
});
